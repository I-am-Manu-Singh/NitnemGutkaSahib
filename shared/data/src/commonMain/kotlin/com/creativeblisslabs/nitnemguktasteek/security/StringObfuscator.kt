        0x65.toByte(), 0x6D.toByte(), 0x47.toByte(), 0x75.toByte(),
        0x74.toByte(), 0x6B.toByte(), 0x61.toByte(), 0x53.toByte()
    )

    fun deobfuscate(encoded: ByteArray): String {
        val out = ByteArray(encoded.size)
        for (i in encoded.indices) {
            val key = SALT_KEYS[i % SALT_KEYS.size].toInt()
            val rotatedKey = (key xor ((i * 17) and 0xFF))
            out[i] = (encoded[i].toInt() xor rotatedKey).toByte()
        }
        return out.decodeToString()
    }

